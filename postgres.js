const D=require('better-sqlite3'),Client=require('pg-native'),crypto=require('crypto');
const pgTypes=require('pg-types');
const migrateSqlite=require('./migrate');

const quoteId=value=>'"'+String(value).replace(/"/g,'""')+'"';
const resultTypes=Object.create(pgTypes);
resultTypes.getTypeParser=(oid,format)=>{
 if(oid===20)return value=>{const parsed=Number(value);if(!Number.isSafeInteger(parsed))throw new Error('PostgreSQL integer result exceeds JavaScript safe integer range');return parsed};
 if(oid===1700)return value=>{const parsed=Number(value);if(!Number.isFinite(parsed))throw new Error('Invalid PostgreSQL numeric result');return parsed};
 return pgTypes.getTypeParser(oid,format)
};
const splitSqlList=sql=>{
 const result=[];let start=0,depth=0,quote=null;
 for(let i=0;i<sql.length;i++){
  const c=sql[i];
  if(quote){if(c===quote){if(sql[i+1]===quote)i++;else quote=null}continue}
  if(c==="'"||c==='"'||c==='`'){quote=c;continue}
  if(c==='(')depth++;
  else if(c===')')depth--;
  else if(c===','&&!depth){result.push(sql.slice(start,i).trim());start=i+1}
 }
 if(sql.slice(start).trim())result.push(sql.slice(start).trim());
 return result
};
const convertCreateTable=(name,sql)=>{
 const start=sql.indexOf('('),end=sql.lastIndexOf(')');
 if(start<0||end<=start)throw new Error(`Cannot convert SQLite table definition for ${name}`);
 const parts=splitSqlList(sql.slice(start+1,end)).filter(part=>!/^constraint\s+\S+\s+foreign\s+key\b/i.test(part)&&!/^foreign\s+key\b/i.test(part));
 const columns=parts.map(part=>{
  let converted=part
   .replace(/\s+references\s+(?:"(?:[^"]|"")*"|[\w.]+)\s*\([^)]*\)(?:\s+on\s+(?:delete|update)\s+\w+)*(?:\s+match\s+\w+)?(?:\s+deferrable(?:\s+initially\s+(?:deferred|immediate))?)?/ig,'')
   .replace(/\binteger\s+primary\s+key\b/i,'bigint generated by default as identity primary key')
   .replace(/\bint\s+primary\s+key\b/i,'bigint generated by default as identity primary key')
   .replace(/\binteger\b/ig,'bigint')
   .replace(/\bint\b/ig,'bigint')
   .replace(/\breal\b/ig,'double precision')
   .replace(/\bblob\b/ig,'bytea');
  if(name==='audit')converted=converted.replace(/^eid\s+bigint\b/i,'eid text');
  return converted
 });
 return `CREATE TABLE ${quoteId(name)} (${columns.join(', ')})`
};
const foreignKeysFor=(sqlite,table)=>{
 const rows=sqlite.prepare(`pragma foreign_key_list(${quoteId(table)})`).all(),groups=new Map();
 for(const row of rows){const group=groups.get(row.id)||[];group.push(row);groups.set(row.id,group)}
 return [...groups.entries()].map(([id,rows])=>{
  rows.sort((a,b)=>a.seq-b.seq);
  const local=rows.map(row=>quoteId(row.from)).join(', '),remote=rows.map(row=>quoteId(row.to)).join(', ');
  const action=value=>({'NO ACTION':'NO ACTION',CASCADE:'CASCADE','SET NULL':'SET NULL','SET DEFAULT':'SET DEFAULT',RESTRICT:'RESTRICT'})[value]||'NO ACTION';
  return `ALTER TABLE ${quoteId(table)} ADD CONSTRAINT ${quoteId(`fk_${table}_${id}`.slice(0,63))} FOREIGN KEY (${local}) REFERENCES ${quoteId(rows[0].table)} (${remote}) ON UPDATE ${action(rows[0].on_update)} ON DELETE ${action(rows[0].on_delete)} DEFERRABLE INITIALLY DEFERRED`
 })
};
const convertTrigger=sql=>{
 const match=sql.match(/create\s+trigger\s+("?[\w]+"?)\s+(before|after)\s+(update|delete)\s+on\s+("?[\w]+"?)\s+begin\s+select\s+raise\(abort,\s*'((?:''|[^'])*)'\)\s*;\s*end\s*;?/i);
 if(!match)throw new Error(`Unsupported SQLite trigger definition: ${sql}`);
 const[,name,timing,event,table,message]=match,fn=`${name.replaceAll('"','')}_fn`.slice(0,63);
 return [
  `CREATE FUNCTION ${quoteId(fn)}() RETURNS trigger LANGUAGE plpgsql AS $transport$ BEGIN RAISE EXCEPTION '%', '${message.replace(/'/g,"''")}' USING ERRCODE='integrity_constraint_violation'; END; $transport$`,
  `CREATE TRIGGER ${quoteId(name.replaceAll('"',''))} ${timing.toUpperCase()} ${event.toUpperCase()} ON ${quoteId(table.replaceAll('"',''))} FOR EACH ROW EXECUTE FUNCTION ${quoteId(fn)}()`
 ]
};
const createSchemaTemplate=()=>{
 const sqlite=new D(':memory:');
 try{
  migrateSqlite(sqlite);
  const objects=sqlite.prepare("select type,name,tbl_name,sql from sqlite_master where name not like 'sqlite_%' and sql is not null order by case type when 'table' then 1 when 'index' then 2 when 'trigger' then 3 else 4 end,name").all();
  const tables=objects.filter(object=>object.type==='table').map(object=>({name:object.name,sql:convertCreateTable(object.name,object.sql),columns:sqlite.prepare(`pragma table_info(${quoteId(object.name)})`).all()}));
  const tableNames=new Set(tables.map(table=>table.name));
  if(tables.length<20)throw new Error('SQLite migration template is incomplete; refusing to initialize PostgreSQL');
  const indexes=objects.filter(object=>object.type==='index'&&object.sql).map(object=>object.sql);
  const foreignKeys=tables.flatMap(table=>foreignKeysFor(sqlite,table.name));
  const triggers=objects.filter(object=>object.type==='trigger').flatMap(object=>convertTrigger(object.sql));
  const migrationRows=sqlite.prepare('select id,at from schema_migrations order by id').all();
  const seedRows=Object.fromEntries(tables.filter(table=>table.name!=='schema_migrations').map(table=>[table.name,sqlite.prepare(`select * from ${quoteId(table.name)}`).all()]).filter(([,rows])=>rows.length));
  const hash=crypto.createHash('sha256').update(JSON.stringify({tables:tables.map(table=>[table.name,table.sql]),indexes,foreignKeys,triggers})).digest('hex');
  return{tables,indexes,foreignKeys,triggers,migrationRows,seedRows,hash}
 }finally{sqlite.close()}
};

const replacePlaceholders=sql=>{
 let result='',index=0,quote=null;
 for(let i=0;i<sql.length;i++){
  const c=sql[i];
  if(quote){
   result+=c;
   if(c===quote){if(sql[i+1]===quote){result+=sql[++i]}else quote=null}
   continue
  }
  if(c==="'"||c==='"'||c==='`'){quote=c;result+=c;continue}
  if(c==='?')result+='$'+(++index);else result+=c
 }
 return result
};
const normalizeSql=sql=>{
 const ignore=/^\s*insert\s+or\s+ignore\s+into\b/i.test(String(sql));
 let text=String(sql).replace(/^\s*insert\s+or\s+ignore\s+into\b/i,'INSERT INTO');
 text=text.replace(/\b([\w."]+)\s*=\s*(\?)\s+collate\s+nocase\b/ig,'lower($1)=lower($2)');
 text=text.replace(/julianday\(t\.departed_at\)\s*>=\s*julianday\('now','-15 minutes'\)/ig,"t.departed_at >= to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC' - INTERVAL '15 minutes','YYYY-MM-DD\"T\"HH24:MI')");
 text=replacePlaceholders(text);
 if(ignore){const returning=text.search(/\sRETURNING\b/i);text=returning<0?text+' ON CONFLICT DO NOTHING':text.slice(0,returning)+' ON CONFLICT DO NOTHING'+text.slice(returning)}
 return text
};
const isInsert=sql=>/^\s*insert\s+(?:or\s+ignore\s+)?into\b/i.test(sql);
const insertTable=sql=>sql.match(/^\s*insert\s+(?:or\s+ignore\s+)?into\s+("?[\w]+"?)/i)?.[1]?.replaceAll('"','');

class PostgresDatabase{
 constructor(url,{schema='public'}={}){
  if(!url)throw new Error('DATABASE_URL is required when DB_BACKEND=postgres');
  if(!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(schema))throw new Error('POSTGRES_SCHEMA must be a PostgreSQL identifier');
  let parsed;
  try{parsed=new URL(url)}catch{throw new Error('DATABASE_URL must be a valid PostgreSQL connection URL')}
  if(!['postgres:','postgresql:'].includes(parsed.protocol))throw new Error('DATABASE_URL must use the postgres:// or postgresql:// scheme');
  const localHost=['','localhost','127.0.0.1','::1'].includes(parsed.hostname.toLowerCase()),sslmode=(parsed.searchParams.get('sslmode')||'').toLowerCase();
  if(process.env.NODE_ENV==='production'&&!localHost&&!['require','verify-ca','verify-full'].includes(sslmode))throw new Error('DATABASE_URL must require TLS for remote PostgreSQL in production (sslmode=require or stricter)');
  this.backend='postgres';this.schema=schema;this.client=new Client({types:resultTypes});this.client.connectSync(url);
  if(schema!=='public')this.client.querySync(`CREATE SCHEMA IF NOT EXISTS ${quoteId(schema)}`);
  this.client.querySync(`SET search_path TO ${quoteId(schema)}`);
  this.idTables=new Set()
 }
 query(sql,params=[]){return this.client.querySync(normalizeSql(sql),params.map(value=>Buffer.isBuffer(value)?'\\x'+value.toString('hex'):value==null?null:String(value)))}
 prepare(sql){
  const db=this;
  return{
   all(...args){return db.query(sql,args)},
   get(...args){return db.query(sql,args)[0]},
   run(...args){
    const table=insertTable(sql),returning=isInsert(sql)&&table&&db.idTables.has(table)&&!/\breturning\b/i.test(sql);
    const text=returning?`${sql.trim().replace(/;$/,'')} RETURNING id`:sql,rows=db.query(text,args);
    return{lastInsertRowid:rows[0]?.id,changes:rows.length}
   }
  }
 }
 exec(sql){for(const statement of String(sql).split(';').map(part=>part.trim()).filter(Boolean))this.query(statement)}
 pragma(){throw new Error('SQLite PRAGMA is not supported by the PostgreSQL backend')}
 transaction(fn){
  const db=this;
  return(...args)=>{
   const depth=db.transactionDepth||0,savepoint=`transport_sp_${depth}`;
   db.query(depth?'SAVEPOINT '+savepoint:'BEGIN');
   db.transactionDepth=depth+1;
   try{const result=fn(...args);db.query(depth?'RELEASE SAVEPOINT '+savepoint:'COMMIT');return result}
   catch(error){try{db.query(depth?'ROLLBACK TO SAVEPOINT '+savepoint:'ROLLBACK')}catch(rollbackError){error.rollbackError=rollbackError}throw error}
   finally{db.transactionDepth=depth}
  }
 }
 close(){this.client.end()}
}

const quoteValue=value=>Buffer.isBuffer(value)?'\\x'+value.toString('hex'):value;
const schemaIsEmpty=db=>db.query("select table_name from information_schema.tables where table_schema=current_schema() and table_type='BASE TABLE' and table_name<>'_transport_schema_version'").length===0;
const ensureSchema=(db,template=createSchemaTemplate(),{seed=true}={})=>{
 const versionTable=db.query("select to_regclass('_transport_schema_version') as name")[0]?.name;
 const version=versionTable?db.query("select schema_hash from _transport_schema_version limit 1"):[];
 if(version.length){
  if(version[0].schema_hash!==template.hash)throw new Error('PostgreSQL schema is from a different application version; run the PostgreSQL migration utility before starting this version.');
  db.idTables=new Set(template.tables.filter(table=>table.columns.some(column=>column.name==='id'&&column.pk===1)).map(table=>table.name));
  return template
 }
 if(!schemaIsEmpty(db))throw new Error('PostgreSQL schema is not empty and has no transport schema marker; refusing to modify it.');
 db.query('BEGIN');
 try{
  for(const table of template.tables)db.query(table.sql);
  for(const index of template.indexes)db.query(index);
  for(const foreignKey of template.foreignKeys)db.query(foreignKey);
  for(const trigger of template.triggers)db.query(trigger);
  if(seed){
   for(const[table,rows]of Object.entries(template.seedRows)){
    const columns=Object.keys(rows[0]),columnSql=columns.map(quoteId).join(', '),placeholders=columns.map((_,index)=>'$'+(index+1)).join(', ');
    for(const row of rows)db.query(`INSERT INTO ${quoteId(table)} (${columnSql}) VALUES (${placeholders})`,columns.map(column=>row[column]));
   }
   for(const row of template.migrationRows)db.query('INSERT INTO schema_migrations(id,at) VALUES($1,$2)',[row.id,row.at]);
  }
  db.query('CREATE TABLE _transport_schema_version(version integer not null, schema_hash text not null)');
  db.query('INSERT INTO _transport_schema_version(version,schema_hash) VALUES(1,$1)',[template.hash]);
  db.query('COMMIT');
  db.idTables=new Set(template.tables.filter(table=>table.columns.some(column=>column.name==='id'&&column.pk===1)).map(table=>table.name));
  return template
 }catch(error){try{db.query('ROLLBACK')}catch(rollbackError){error.rollbackError=rollbackError}throw error}
};

module.exports={PostgresDatabase,createSchemaTemplate,ensureSchema,quoteId,quoteValue};
